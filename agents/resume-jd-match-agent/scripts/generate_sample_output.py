"""Runs the agent once on a resume + JD and saves the report.

Uses 2 Gemini requests. Run from agents/resume-jd-match-agent/:
    python scripts/generate_sample_output.py
    python scripts/generate_sample_output.py --resume my_cv.pdf --jd samples/sample_jd_frontend.txt --out report.md
"""

import argparse
import asyncio
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from dotenv import load_dotenv  # noqa: E402  (installed with google-adk)

load_dotenv(os.path.join(ROOT, "resume_jd_agent", ".env"))

from google.adk.runners import InMemoryRunner  # noqa: E402
from google.genai import types  # noqa: E402

from resume_jd_agent.agent import root_agent  # noqa: E402


async def run(resume: str, jd: str) -> str:
    runner = InMemoryRunner(agent=root_agent, app_name="resume_jd_agent")
    session = await runner.session_service.create_session(app_name="resume_jd_agent", user_id="cli")
    message = types.Content(role="user", parts=[types.Part(text=f"Resume: {resume}\nJob description: {jd}")])
    report, model_calls = "", 0
    async for event in runner.run_async(user_id="cli", session_id=session.id, new_message=message):
        if event.author == root_agent.name and event.usage_metadata:
            model_calls += 1
        for call in event.get_function_calls() or []:
            print(f"tool call: {call.name}({', '.join(f'{k}={v!r}' for k, v in call.args.items())})", file=sys.stderr)
        if event.is_final_response() and event.content and event.content.parts:
            report = "".join(p.text or "" for p in event.content.parts if not p.thought)
    print(f"Gemini requests used: {model_calls}", file=sys.stderr)
    return report.strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--resume", default="samples/sample_resume.txt", help=".pdf or .txt path")
    parser.add_argument("--jd", default="samples/sample_jd.txt", help=".txt path")
    parser.add_argument("--out", default="samples/sample_output.md", help="where to save the report")
    args = parser.parse_args()

    report = asyncio.run(run(args.resume, args.jd))
    header = (
        f"<!-- Generated by scripts/generate_sample_output.py with {root_agent.model.model} "
        f"on {os.path.basename(args.resume)} and {os.path.basename(args.jd)}. -->\n\n"
    )
    with open(args.out, "w") as f:
        f.write(header + report + "\n")
    print(report)
    print(f"\nSaved to {args.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
